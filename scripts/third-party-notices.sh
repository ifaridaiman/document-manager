#!/bin/sh
# Regenerates THIRD_PARTY_NOTICES.md for the pdf-engine binary.
#   sh scripts/third-party-notices.sh
# Go module licenses are copied verbatim from the module cache for the exact
# versions compiled in (`go version -m`); the native libraries inside go-pdfium's
# embedded pdfium.wasm are listed by hand below. Rerun after dependency upgrades.
set -eu
cd "$(dirname "$0")/.."
OUT=THIRD_PARTY_NOTICES.md
MOD=$(go env GOMODCACHE)
BIN=$(mktemp)
trap 'rm -f "$BIN"' EXIT
go build -o "$BIN" ./cmd/pdf-engine
GOVER=$(go version -m "$BIN" | head -1 | awk '{print $2}')
# Go's LICENSE text is the same in every release; find a copy (Homebrew keeps it one level up).
GOROOT=$(go env GOROOT)
GOLICENSE=$(ls "$GOROOT/LICENSE" "$GOROOT/../LICENSE" "$MOD"/golang.org/toolchain@*/LICENSE 2>/dev/null | head -1)
[ -n "$GOLICENSE" ] || { echo "cannot find Go's LICENSE" >&2; exit 1; }

cat > "$OUT" <<'EOF'
# Third-party notices

The pdf-engine binary (and the npm packages and GitHub release files that ship
it) contains the software listed below. The MIT license in `LICENSE` covers
document-manager's own code only; each component here keeps its own license.

This file is generated by `scripts/third-party-notices.sh`.

