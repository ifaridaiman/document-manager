## Go modules compiled into the binary

EOF

section() { # title, license file
  printf '### %s\n\n```\n' "$1" >> "$OUT"
  cat "$2" >> "$OUT"
  printf '```\n\n' >> "$OUT"
}

section "Go standard library ($GOVER)" "$GOLICENSE"
go version -m "$BIN" | awk '$1 == "dep" {print $2 "@" $3}' | while read -r dep; do
  dir="$MOD/$(echo "$dep" | sed 's/[A-Z]/!&/g' | tr 'A-Z' 'a-z')" # module cache escapes capitals
  lic=$(ls "$dir"/LICENSE* "$dir"/COPYING* 2>/dev/null | head -1)
  [ -n "$lic" ] || { echo "no license file for $dep" >&2; exit 1; }
  # Apache-2.0 modules: the full text appears once at the end, plus any NOTICE.
  if grep -q "Apache License" "$lic" && grep -q "Version 2.0" "$lic"; then
    printf '### %s\n\nApache License 2.0 (full text at the end of this file).\n\n' "$dep" >> "$OUT"
    [ -f "$dir/NOTICE" ] && { printf 'NOTICE:\n\n```\n' >> "$OUT"; cat "$dir/NOTICE" >> "$OUT"; printf '```\n\n' >> "$OUT"; }
  else
    section "$dep" "$lic"
  fi
done

printf '## Apache License 2.0\n\nApplies to PDFium (with BSD-3-Clause above), Abseil, and the Apache-2.0 Go modules above.\n\n```\n' >> "$OUT"
cat "$MOD/github.com/tetratelabs/wazero@$(go list -m -f '{{.Version}}' github.com/tetratelabs/wazero)/LICENSE" >> "$OUT"
printf '```\n' >> "$OUT"
echo "wrote $OUT"
